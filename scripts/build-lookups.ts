// Writes src/data/lookups.data.ts from Kuni: alpha-3, numeric and IOC codes, folded names, and the flag emoji.
// Run it with Kuni 1.18.0 or newer (the devDependency may be older; point KUNI_ENTRY at that package's dist):
//
//   KUNI_ENTRY=/path/to/kuni/dist/index.js node scripts/build-lookups.ts
//
// A code or a folded name that two places hold is left out, so a lookup never guesses. FIFA codes are not in
// Kuni, so they are not a list here. The drawings are not read.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { FLAG_ALIASES } from "../src/data/aliases.data.ts";
import { NAMES } from "../src/data/names.data.ts";
import { foldKey } from "../src/nameFold.ts";

interface Country {
  alpha2: string;
  alpha3: string;
  numeric: string;
  name: { en: string; ja: string; local?: string };
  shortName?: { en?: string; ja?: string };
  reading?: string;
  aliases?: string[];
  ioc?: string;
  flag: string;
}

const ROOT = join(import.meta.dirname, "..");
const entry = process.env.KUNI_ENTRY ?? "@johnmorrisdotca/kuni";
const kuni = (await import(entry.startsWith("@") ? entry : pathToFileURL(entry).href)) as { countries(): Country[] };
const countries = kuni.countries();
if (!countries.some((country) => country.ioc !== undefined)) throw new Error("This Kuni has no IOC codes. Point KUNI_ENTRY at Kuni 1.18.0 or newer.");

const flags = new Set(Object.keys(NAMES));

/** Record a key for a code. A second, different code for the same key is a collision and the key is dropped. */
const fill = (map: Map<string, string>, dropped: Set<string>, key: string, code: string): void => {
  if (key === "") return;
  const previous = map.get(key);
  if (previous === undefined) map.set(key, code);
  else if (previous !== code) dropped.add(key);
};

const codes = new Map<string, string>();
const codeClashes = new Set<string>();
for (const country of countries) {
  if (!flags.has(country.alpha2)) continue;
  fill(codes, codeClashes, country.alpha3, country.alpha2);
  fill(codes, codeClashes, country.numeric, country.alpha2);
  if (country.ioc !== undefined) fill(codes, codeClashes, country.ioc, country.alpha2);
}
for (const [alias, code] of Object.entries(FLAG_ALIASES)) {
  const previous = codes.get(alias);
  if (previous !== undefined && previous !== code) codeClashes.add(alias);
}
for (const key of codeClashes) codes.delete(key);

const names = new Map<string, string>();
const nameClashes = new Set<string>();
for (const [code, [en, ja]] of Object.entries(NAMES)) {
  fill(names, nameClashes, foldKey(en), code);
  fill(names, nameClashes, foldKey(ja), code);
}
for (const country of countries) {
  if (!flags.has(country.alpha2)) continue;
  const texts = [country.name.en, country.name.ja, country.name.local, country.shortName?.en, country.shortName?.ja, country.reading, ...(country.aliases ?? [])];
  for (const text of texts) if (text !== undefined) fill(names, nameClashes, foldKey(text), country.alpha2);
}
for (const key of nameClashes) names.delete(key);

// England, Scotland and Wales have Unicode tag sequences. Northern Ireland has none, and no flag here.
const TAG_REGIONS: Readonly<Record<string, string>> = { "GB-ENG": "gbeng", "GB-SCT": "gbsct", "GB-WLS": "gbwls" };
const tagFlag = (region: string): string => `\u{1F3F4}${[...region].map((letter) => String.fromCodePoint(0xe0000 + letter.charCodeAt(0))).join("")}\u{E007F}`;

const emoji = new Map<string, string>();
for (const country of countries) if (flags.has(country.alpha2)) emoji.set(country.alpha2, country.flag);
for (const [code, region] of Object.entries(TAG_REGIONS)) if (flags.has(code)) emoji.set(code, tagFlag(region));

const record = (map: Map<string, string>): string =>
  [...map.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([key, code]) => `  ${JSON.stringify(key)}: ${JSON.stringify(code)},`)
    .join("\n");

const dropped = [...nameClashes].sort();
writeFileSync(
  join(ROOT, "src/data/lookups.data.ts"),
  `// Generated by scripts/build-lookups.ts from Kuni 1.18.0. Do not edit by hand.
// A code or a folded name that two places hold is absent (${dropped.length} names dropped, ${codeClashes.size} codes). FIFA codes are not in Kuni.

/** Alpha-3, numeric and IOC codes that name one current flag. */
const CODE_LOOKUP: Readonly<Record<string, string>> = {
${record(codes)}
};

/** Folded English and Japanese names, short names, readings and aliases that name one flag. */
const NAME_LOOKUP: Readonly<Record<string, string>> = {
${record(names)}
};

/** A country flag as emoji, and the tag sequences for England, Scotland and Wales. */
const FLAG_EMOJI: Readonly<Record<string, string>> = {
${record(emoji)}
};

export { CODE_LOOKUP, FLAG_EMOJI, NAME_LOOKUP };
`,
);

console.log(`codes ${codes.size}, names ${names.size}, emoji ${emoji.size}, names dropped ${dropped.length}: ${dropped.slice(0, 12).join(", ")}`);
