// Writes src/data/name-languages/<language>.data.ts and src/names/<language>.ts from Kuni's
// CLDR name tables. English and Japanese stay in src/names.ts. Run it with Kuni's repository
// (origin/main must already have src/data/names/<language>.data.ts):
//
//   KUNI_REPO=/path/to/kuni node scripts/build-name-languages.ts
//
// Nothing is downloaded. A place this package has no flag for is left out. A former country's
// alias is copied only when the place it points at has a name in that language.

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { FLAG_ALIASES } from "../src/data/aliases.data.ts";
import { NAMES } from "../src/data/names.data.ts";

const LANGUAGES = ["fr", "es", "de", "zh-Hans", "zh-Hant", "ko", "pt", "ar", "ru"] as const;

const ENGLISH: Readonly<Record<(typeof LANGUAGES)[number], string>> = {
  fr: "French",
  es: "Spanish",
  de: "German",
  "zh-Hans": "Simplified Chinese",
  "zh-Hant": "Traditional Chinese",
  ko: "Korean",
  pt: "Portuguese",
  ar: "Arabic",
  ru: "Russian",
};

const repo = process.env.KUNI_REPO;
if (repo === undefined || repo === "") throw new Error("Set KUNI_REPO to the Kuni repository. Its origin/main must have src/data/names.");

const flags = new Set(Object.keys(NAMES));
const root = join(import.meta.dirname, "..");

const kuniNames = (language: string): Record<string, string> => {
  const text = execFileSync("git", ["-C", repo, "show", `origin/main:src/data/names/${language}.data.ts`], { encoding: "utf8" });
  const names: Record<string, string> = {};
  for (const match of text.matchAll(/^\s{4}([A-Z]{2}): \["((?:\\.|[^"\\])*)"/gm)) names[match[1]] = JSON.parse(`"${match[2]}"`) as string;
  if (Object.keys(names).length < 200) throw new Error(`${language} parsed ${Object.keys(names).length} names`);
  return names;
};

const constName = (language: string): string => `NAMES_${language.toUpperCase().replace("-", "_")}`;

mkdirSync(join(root, "src/data/name-languages"), { recursive: true });
mkdirSync(join(root, "src/names"), { recursive: true });

for (const language of LANGUAGES) {
  const fromKuni = kuniNames(language);
  const table: Record<string, string> = {};
  for (const code of flags) {
    const name = fromKuni[code];
    if (name !== undefined) table[code] = name;
  }
  for (const [alias, code] of Object.entries(FLAG_ALIASES)) if (table[alias] === undefined && table[code] !== undefined) table[alias] = table[code];
  const body = Object.keys(table).sort().map((code) => `  ${JSON.stringify(code)}: ${JSON.stringify(table[code])},`).join("\n");
  writeFileSync(
    join(root, "src/data/name-languages", `${language}.data.ts`),
    `// Generated by scripts/build-name-languages.ts. Do not edit by hand.\n// Country names in ${ENGLISH[language]}, from Kuni's Unicode CLDR table (@johnmorrisdotca/kuni/names/${language}).\n// Only a place this package has a flag for. A place with no name in this language is absent.\n\nexport const ${constName(language)}: Readonly<Record<string, string>> = {\n${body}\n};\n`,
  );
  writeFileSync(
    join(root, "src/names", `${language}.ts`),
    `// The entry @johnmorrisdotca/hata/names/${language}: a country's name in ${ENGLISH[language]}, from Kuni's\n// Unicode CLDR table. English and Japanese stay in /names. A page that asks for this language pays\n// for this entry and not for the others.\n\nimport { ${constName(language)} } from "../data/name-languages/${language}.data";\nimport { flagNameIn } from "./extra";\n\n/**\n * The name of a country in ${ENGLISH[language]}, as Kuni gives it from Unicode CLDR. A prefecture, a former\n * country, and any place Kuni does not name in ${ENGLISH[language]} is null.\n *\n * @param code - A flag's code, in any case: "JP", "jp", "DE". A former country's alias is read when that place has a name here.\n * @returns The ${ENGLISH[language]} name, or null when this language has no name for that flag.\n * @throws TypeError when \`code\` is not a string.\n *\n * @example\n * \`\`\`ts\n * import { flagName } from "@johnmorrisdotca/hata/names/${language}";\n *\n * console.log(flagName("JP"));\n * console.log(flagName("JP-13"));\n * \`\`\`\n */\nconst flagName = (code: string): string | null => flagNameIn(${constName(language)}, code);\n\nexport { flagName };\n`,
  );
  console.log(`${language} ${Object.keys(table).length}`);
}
