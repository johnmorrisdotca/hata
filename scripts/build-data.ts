const commonsText = (file: CommonsFile): string => {
  const bytes = readFileSync(join(SOURCES_DIR, file.stored));
  if (sha256(bytes) !== file.sha256) throw new Error(`data-sources/${file.stored} is not the file the Commons snapshot recorded`);

  return bytes.toString("utf8");
};

// A Commons file's licence, with the maintainer's decisions in data-config.ts laid over it.
const licenceOf = (file: CommonsFile): Licence => {
  const classified = classify(file.metadata, file.templates);
  const decision = ACCEPTED[file.file];
  if (classified.shipped || decision === undefined) return classified;

  return { shipped: true, kind: classified.publicDomainTemplate ? "public-domain" : "accepted", name: `${classified.name} (accepted: ${decision})`, url: classified.url };
};

// The drawing a choice names, with what is known about where it comes from and its terms.
const drawingOf = (place: Place, choice: Choice, reference: CommonsFile, referenceLicence: Licence): Drawing => {
  if (choice.source === "commons") {
    if (choice.file !== reference.file) throw new Error(`${place.code}: choices.data.json names ${choice.file}, but Wikidata names ${reference.file}: run pnpm data:choose ${place.code}`);
    if (!referenceLicence.shipped) throw new Error(`${place.code}: choices.data.json ships Commons' file, whose licence is ${referenceLicence.name}`);
    const metadata = reference.metadata;
    return {
      key: `commons:${reference.file}`,
      source: "commons",
      file: reference.file,
      page: reference.page,
      version: null,
      licence: { kind: referenceLicence.kind, name: referenceLicence.name, url: referenceLicence.url },
      author: metadata.Artist ?? null,
      credit: metadata.Credit ?? null,
      attributionRequired: metadata.AttributionRequired === "true",
      templates: reference.templates.map((template) => template.replace(/^Template:/, "")),
      uploaded: reference.uploaded.slice(0, 10),
      bytes: reference.bytes,
      text: commonsText(reference),
    };
  }
  const candidate = setCandidates(place.code).find((one) => one.source === choice.source && one.file === choice.file);
  if (candidate === undefined) throw new Error(`${place.code}: ${choice.source} has no ${choice.file}: run pnpm data:choose ${place.code}`);
  const set = setNamed(candidate.source);

  return {
    key: `${candidate.source}:${candidate.file}`,
    source: choice.source!,
    file: candidate.file,
    page: candidate.page,
    version: set.version,
    licence: { kind: "mit", name: "MIT", url: `https://cdn.jsdelivr.net/npm/${set.name}@${set.version}/LICENSE` },
    author: set.copyright,
    credit: `${set.name} ${set.version}, ${set.home}`,
    attributionRequired: true,
    templates: [],
    uploaded: null,
    bytes: Buffer.byteLength(candidate.text),
    text: candidate.text,
  };
};

// 3. Each place's flag, or why it has none.
const shipped: Shipped[] = [];
const leftOut: LeftOut[] = [];
const chosen: { place: Place; drawing: Drawing; reference: CommonsFile; referenceLicence: Licence; item: string; choice: Choice; named?: string }[] = [];
for (const place of places) {
  const selection = selectPlace(place.code, wikidata);
  const handWritten = NO_FLAG[place.code];
  if (handWritten !== undefined) {
    leftOut.push({ place, kind: "no-flag", reason: handWritten });
    continue;
  }
  if (selection.file === null) {
    leftOut.push({ place, kind: "no-flag", reason: selection.reason });
    continue;
  }
  const reference = commonsByFile.get(selection.file);
  if (reference === undefined) throw new Error(`${place.code}: ${selection.file} is not in the Commons snapshot: run pnpm data:commons`);
  if (reference.mime !== "image/svg+xml") {
    leftOut.push({ place, kind: "not-svg", reason: `Wikidata's flag image is a ${reference.mime} file, not an SVG`, file: reference });
    continue;
  }
  const referenceLicence = licenceOf(reference);
  const choice = CHOICES[place.code];
  if (choice === undefined) throw new Error(`${place.code} has no line in scripts/choices.data.json: run pnpm data:choose ${place.code}`);
  if (choice.source === null) {
    leftOut.push({ place, kind: "licence", reason: `Commons gives its licence as ${referenceLicence.name}, which is not public domain, CC0 or CC BY, and no MIT flag set draws the same flag at its proportions`, file: reference, licence: referenceLicence });
    continue;
  }
  chosen.push({ place, drawing: drawingOf(place, choice, reference, referenceLicence), reference, referenceLicence, item: selection.item!, choice, ...(selection.rule === "named" ? { named: selection.why } : {}) });
}

// Which place a shared drawing belongs to: a country whose English name is in the file's name, else the first
// country, else the first place. "Flag of France.svg" is France's, whoever else flies it.
const ownerByKey = new Map<string, string>();
const users = new Map<string, Place[]>();
for (const { place, drawing } of chosen) users.set(drawing.key, [...(users.get(drawing.key) ?? []), place]);
for (const [key, list] of users) {
  const countries = list.filter((user) => user.group === "country");
  const named = countries.find((user) => key.toLowerCase().includes(user.en.toLowerCase()));
  ownerByKey.set(key, (named ?? countries[0] ?? list[0]!).code);
}

const optimisedByKey = new Map<string, Optimised>();
for (const { place, drawing, reference, referenceLicence, item, choice, named } of chosen) {
  const owner = ownerByKey.get(drawing.key)!;
  let optimised = optimisedByKey.get(drawing.key);
  if (optimised === undefined) {
    optimised = optimiseFlag(drawing.text, owner, { ...(choice.precision === undefined ? {} : { precision: choice.precision }), ...(choice.keepPaths ? { keepPaths: true } : {}) });
    // The picture names its flag, so that frame() can frame it the way measured for it (FRAMINGS).
    optimised = { ...optimised, svg: optimised.svg.replace(/^<svg\b/, `<svg data-hata="${owner.toLowerCase()}"`) };
    optimisedByKey.set(drawing.key, optimised);
  }
  const bytes = Buffer.byteLength(optimised.svg);
  if (bytes > CEILING_BYTES) throw new Error(`${place.code}: ${KB(bytes)} after optimising, over the ceiling of ${KB(CEILING_BYTES)}`);
  shipped.push({ place, drawing, reference, referenceLicence, item, optimised, owner, gzip: gzipSync(optimised.svg, { level: 9 }).length, why: named === undefined ? choice.why : `Named by hand: ${named} ${choice.why}`, compared: choice.compared, designDiffers: choice.designDiffers ?? [] });
}
shipped.sort(byCode);

const owners = shipped.filter((one) => one.owner === one.place.code);

// How each picture is framed at 4:3, square and round (scripts/framing.mjs, `pnpm data:framing`), and the
// hand-adapted drawings that ship for the frames that use one.
type FramedShape = "4:3" | "1:1" | "round";
const FRAMED_SHAPES: FramedShape[] = ["4:3", "1:1", "round"];
interface Framing {
  method: "own" | "adapted" | "cover" | "crop" | "contain";
  fit: "cover" | "crop" | "contain";
  crop: { rule: "own" | "curated" | "centre" | "whole"; at: Anchor; loses?: string[] };
  source?: "flag-icons";
  file?: string;
  precision?: number;
  keepPaths?: boolean;
  coverLoses?: string[];
  refused?: string;
}
const FRAMINGS_FILE = JSON.parse(readFileSync(join(ROOT, "scripts", "framings.data.json"), "utf8")) as Record<string, Record<FramedShape, Framing>>;
const shapeName = (shape: "4:3" | "1:1"): string => shape.replace(":", "x");
interface Adapted {
  owner: string;
  shape: "4:3" | "1:1";
  module: string; // "ca.1x1"
  file: string;
  page: string;
  version: string;
  optimised: Optimised;
  raw: number;
}
const adapted: Adapted[] = [];
const unmeasuredFlags: string[] = [];
for (const one of owners) {
  const framing = FRAMINGS_FILE[one.place.code];
  if (framing === undefined || FRAMED_SHAPES.some((shape) => framing[shape] === undefined)) {
    // Not measured yet (a flag new to this build: scripts/framing.mjs reads this build's records, so it cannot measure it before). Everything is
    // written as if it were cropped from the centre, and the build stops at its end, naming what to measure.
    unmeasuredFlags.push(one.place.code);
    const placeholder: Framing = { method: "cover", fit: "cover", crop: { rule: "centre", at: "centre" } };
    FRAMINGS_FILE[one.place.code] = { "4:3": placeholder, "1:1": placeholder, round: placeholder };
    continue;
  }
  for (const shape of ["4:3", "1:1"] as const) {
    const entry = framing[shape];
    if (entry.method !== "adapted") continue;
    const candidate = setCandidates(one.place.code).find((option) => option.source === entry.source && option.file === entry.file);
    if (candidate === undefined) throw new Error(`${one.place.code}: ${entry.source} has no ${entry.file}: run pnpm data:framing ${one.place.code}`);
    const module = `${moduleName(one.place.code)}.${shapeName(shape)}`;
    const optimised = optimiseFlag(candidate.text, `${one.place.code}-${shapeName(shape)}`, { ...(entry.precision === undefined ? {} : { precision: entry.precision }), ...(entry.keepPaths ? { keepPaths: true } : {}) });
    if (Buffer.byteLength(optimised.svg) > CEILING_BYTES) throw new Error(`${module}: ${KB(Buffer.byteLength(optimised.svg))} after optimising, over the ceiling of ${KB(CEILING_BYTES)}`);
    adapted.push({ owner: one.place.code, shape, module, file: candidate.file, page: candidate.page, version: setNamed(candidate.source).version, optimised, raw: Buffer.byteLength(candidate.text) });
  }
}
const framingOf = (one: Shipped): Record<FramedShape, Framing> => FRAMINGS_FILE[one.owner]!;
const adaptedFor = (one: Shipped, shape: FramedShape): Adapted | undefined => adapted.find((entry) => entry.owner === one.owner && entry.shape === (shape === "round" ? "1:1" : shape) && framingOf(one)[shape].method === "adapted");

// 3b. Each place's other flags in real use (VARIANTS in data-config.ts): the drawing of each is fetched and licence-checked
// like any flag's, shipped as its own module (`<code>--<id>`), or as the module of the picture it shares with a flag.
interface VariantRecord {
  id: string;
  name: string;
  nameJa: string;
  status: string;
  from: string | null;
  until: string | null;
  why: string;
  source: string;
  default: boolean;
  module: string;
  frames: Record<"4:3" | "1:1" | "round", "cover" | "crop" | "contain">;
  drawing: { source: string; file: string; page: string; licence: ShippedLicence; author: string | null; credit: string | null; attributionRequired: boolean; restrictions: string[]; uploaded: string | null; width: number; height: number; bytes: number };
}
interface VariantModule {
  module: string; // "af--de-facto"
  owner: string | null; // the module whose picture it is, where a flag has the same drawing
  drawing: Drawing;
  optimised: Optimised | null;
  name: string;
  spec: string;
}
const variantSets = new Map<string, { disputed: boolean; default: string | null; variants: VariantRecord[] }>();
const variantModules: VariantModule[] = [];
const variantsLeftOut: { code: string; id: string; file: string; reason: string }[] = [];
const shippedByCode = new Map(shipped.map((one) => [one.place.code, one]));
const variantKeyFor = (code: string): string | null => (VARIANTS[code] !== undefined ? code : SAME_PLACE[code] !== undefined && VARIANTS[SAME_PLACE[code]!] !== undefined ? SAME_PLACE[code]! : null);
const commonsDrawing = (file: CommonsFile, licence: Licence): Drawing => {
  if (!licence.shipped) throw new Error(`${file.file}: licence ${licence.name} is not one that ships`);

  return {
    key: `commons:${file.file}`,
    source: "commons",
    file: file.file,
    page: file.page,
    version: null,
    licence: { kind: licence.kind, name: licence.name, url: licence.url },
    author: file.metadata.Artist ?? null,
    credit: file.metadata.Credit ?? null,
    attributionRequired: file.metadata.AttributionRequired === "true",
    templates: file.templates.map((template) => template.replace(/^Template:/, "")),
    uploaded: file.uploaded.slice(0, 10),
    bytes: file.bytes,
    text: commonsText(file),
  };
};
for (const [code, set] of Object.entries(VARIANTS)) {
  const ids = set.variants.map((variant) => variant.id);
  if (new Set(ids).size !== ids.length) throw new Error(`VARIANTS ${code}: two variants share an id`);
  if (!ids.every((id) => /^[a-z0-9]+(-[a-z0-9]+)*$/.test(id))) throw new Error(`VARIANTS ${code}: an id is not kebab case`);
  if (set.default !== null && !ids.includes(set.default)) throw new Error(`VARIANTS ${code}: default ${set.default} is not one of its variants`);
  const own = set.variants.filter((variant) => variant.file === null);
  const place = shippedByCode.get(code);
  if (set.default === null) {
    if (own.length > 0 || place !== undefined) throw new Error(`VARIANTS ${code}: no default means the place has no flag of its own, and every variant names a file`);
  } else if (place === undefined || own.length !== 1 || own[0]!.id !== set.default) throw new Error(`VARIANTS ${code}: its default must be its one variant with no file, and the place must have a flag here`);
  const records: VariantRecord[] = [];
  for (const spec of set.variants) {
    const base = { id: spec.id, name: spec.name, nameJa: spec.nameJa, status: spec.status, from: spec.from, until: spec.until, why: spec.why, source: spec.source, default: spec.id === set.default };
    if (spec.file === null) {
      const one = place!;
      const measured = FRAMINGS_FILE[one.owner]!;
      records.push({ ...base, module: moduleName(code), frames: { "4:3": measured["4:3"].fit, "1:1": measured["1:1"].fit, round: measured.round.fit }, drawing: { source: one.drawing.source, file: one.drawing.file, page: one.drawing.page, licence: one.drawing.licence, author: one.drawing.author, credit: one.drawing.credit, attributionRequired: one.drawing.attributionRequired, restrictions: restrictionsOf(one.reference.metadata), uploaded: one.drawing.uploaded, width: one.optimised.width, height: one.optimised.height, bytes: size(one) } });
      continue;
    }
    const file = commonsByFile.get(spec.file);
    if (file === undefined) throw new Error(`VARIANTS ${code} ${spec.id}: ${spec.file} is not in the Commons snapshot: run pnpm data:commons`);
    const licence = licenceOf(file);
    if (file.mime !== "image/svg+xml" || !licence.shipped) {
      variantsLeftOut.push({ code, id: spec.id, file: spec.file, reason: file.mime !== "image/svg+xml" ? `a ${file.mime} file, not an SVG` : `licence ${licence.name}` });
      continue;
    }
    const drawing = commonsDrawing(file, licence);
    const module = `${moduleName(code)}--${spec.id}`;
    const sharer = shipped.find((one) => one.drawing.key === drawing.key);
    let optimised: Optimised | null = null;
    if (sharer === undefined) {
      optimised = optimiseFlag(drawing.text, `${code}--${spec.id}`, {});
      optimised = { ...optimised, svg: optimised.svg.replace(/^<svg\b/, `<svg data-hata="${module}"`) };
      if (Buffer.byteLength(optimised.svg) > CEILING_BYTES) throw new Error(`${module}: ${KB(Buffer.byteLength(optimised.svg))} after optimising, over the ceiling of ${KB(CEILING_BYTES)}`);
    }
    const picture = sharer?.optimised ?? optimised!;
    variantModules.push({ module, owner: sharer === undefined ? null : moduleName(sharer.owner), drawing, optimised, name: spec.name, spec: `${code} ${spec.id}` });
    const measured = FRAMINGS_FILE[sharer?.owner ?? `${code}--${spec.id}`];
    const frames = measured === undefined ? ({ "4:3": "cover", "1:1": "cover", round: "cover" } as const) : ({ "4:3": measured["4:3"].fit, "1:1": measured["1:1"].fit, round: measured.round.fit } as const);
    records.push({ ...base, module, frames, drawing: { source: "commons", file: drawing.file, page: drawing.page, licence: drawing.licence, author: drawing.author, credit: drawing.credit, attributionRequired: drawing.attributionRequired, restrictions: restrictionsOf(file.metadata), uploaded: drawing.uploaded, width: picture.width, height: picture.height, bytes: Buffer.byteLength(picture.svg) } });
  }
  variantSets.set(code, { disputed: set.disputed, default: set.default, variants: records });
}
const variantsOfCode = (code: string): { disputed: boolean; default: string | null; variants: VariantRecord[] } => variantSets.get(variantKeyFor(code) ?? "") ?? { disputed: false, default: null, variants: [] };
leftOut.sort(byCode);

// 4. The source files.
const quote = (text: string): string => JSON.stringify(text);
const ratio = (width: number, height: number): string => {
  const known: [number, string][] = [[1, "1:1"], [4 / 3, "4:3"], [3 / 2, "3:2"], [5 / 3, "5:3"], [8 / 5, "8:5"], [5 / 4, "5:4"], [7 / 4, "7:4"], [13 / 7, "13:7"], [19 / 10, "19:10"], [2, "2:1"], [11 / 8, "11:8"], [7 / 5, "7:5"], [10 / 7, "10:7"], [9 / 7, "9:7"], [15 / 11, "15:11"], [18 / 11, "18:11"], [11 / 6, "11:6"], [5 / 2, "5:2"], [22 / 13, "22:13"], [28 / 37, "28:37"]];
  const value = width / height;
  const near = known.find(([target]) => Math.abs(target - value) / target < 0.002);

  return near ? near[1] : `${value.toFixed(3)}:1`;
};
const licenceWords = (licence: ShippedLicence): string => (licence.kind === "public-domain" ? "public domain" : licence.name);
const sourceWords = (drawing: Drawing): string => (drawing.source === "commons" ? `Wikimedia Commons, "${drawing.file}"` : `${drawing.source} ${drawing.version}, ${drawing.file}`);

const docOf = (one: Shipped): string => {
  const { place, optimised } = one;
  const shared = one.owner !== place.code ? ` The same picture as ${one.owner}'s.` : "";
  const name = `${place.en}${place.ja ? ` (${place.ja})` : ""}`;

  return `/**
 * The flag of ${name}, ${place.code}, as an SVG string: viewBox ${optimised.width} by ${optimised.height} (${ratio(optimised.width, optimised.height)}), ${KB(Buffer.byteLength(optimised.svg))}.${shared}
 * From ${sourceWords(one.drawing)} (${licenceWords(one.drawing.licence)}); the /manifest entry gives its author, licence and why it was chosen.
 * It has a viewBox and no width or height, so it fills the box it is put in at its own aspect ratio.
 *
 * @example
 * \`\`\`ts
 * import flag from "@johnmorrisdotca/hata/flags/${moduleName(place.code)}";
 *
 * element.innerHTML = flag; // or toDataUri(flag) from "@johnmorrisdotca/hata" for an <img src>
 * \`\`\`
 */`;
};

