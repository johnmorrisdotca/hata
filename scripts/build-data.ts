// Builds the flags from the inputs kept in data-sources/ and the flag sets in node_modules, with no network and no
// browser:
//
//   pnpm data            writes src/flags/<code>.ts, src/data/*.data.ts, the docs that list the flags, and the
//                        credits and licences in NOTICE.md
//
// For every code Kuni knows (each country, and the first level of the countries in SUBDIVISION_COUNTRIES):
//
//   1. the Commons file Wikidata names as its flag (scripts/select.ts), or the reason there is none, checked
//      against the SHA-256 the Commons snapshot recorded: the reference drawing, at the flag's true proportions;
//   2. the drawing chosen to ship, from scripts/choices.data.json (written by `pnpm data:choose`, which compares
//      Commons' drawing with flag-icons', country-flag-icons' and circle-flags' in a browser): Commons', or a
//      set's where it is the same flag at the same proportions and smaller, or free where Commons' is not;
//   3. that drawing optimised and made safe to inline (scripts/optimise.ts) at the precision the choice records,
//      and measured against the size budget.
//
// Places that share one drawing (Guadeloupe and France, Bouvet Island and Norway) share one picture: the flag's
// own module carries it and the other re-exports it. Run twice, it leaves the tree as it was.

