const sourceNamed = (pattern: RegExp): string => {
  const entry = manifest.files.find((file) => pattern.test(file.path));
  if (entry === undefined) throw new Error(`no ${pattern} in data-sources/sources.json`);

  return readSource(manifest, entry.path).text;
};
const wikidata = JSON.parse(sourceNamed(/^wikidata-\d{4}-\d{2}-\d{2}\.json$/)) as WikidataSnapshot & { read: string };
